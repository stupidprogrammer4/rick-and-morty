def apply_style(connection: sa.Connection) -> None:
    rows = connection.execute(
        sa.text(
            "SELECT v.id, d.`key`, v.scope, v.value "
            "FROM tbl_setting_values v "
            "JOIN tbl_setting_definitions d ON d.id=v.definition_id "
            "WHERE (d.`key` IN ('automation.policy','occasions.policy') "
            "AND v.scope='global') "
            "OR (d.`key`='post.style' AND v.scope='news')"
        )
    ).all()
    for id, key, scope, raw in rows:
        value = json.loads(raw)
        before = json.dumps(value, sort_keys=True)
        if key == "automation.policy":
            value["news"].update(
                system_prompt=RICK_NEWS_SYSTEM_PROMPT,
                prompt=RICK_NEWS_PROMPT,
            )
        elif key == "occasions.policy":
            value.update(
                system_prompt=RICK_OCCASION_SYSTEM_PROMPT,
                prompt=RICK_OCCASION_PROMPT,
            )
        else:
            value.update(NEWS_POST_STYLE)
        if json.dumps(value, sort_keys=True) != before:
            connection.execute(
                sa.text(
                    "UPDATE tbl_setting_values SET value=:value, "
                    "revision=revision+1, updated_at=CURRENT_TIMESTAMP "
                    "WHERE id=:id"
                ),
                {"id": id, "value": json.dumps(value, ensure_ascii=False)},
            )
    connection.execute(
        sa.text(
            "UPDATE tbl_publications p "
            "JOIN tbl_drafts d ON d.id=p.draft_id "
            "JOIN tbl_missions m ON m.id=d.mission_id "
            "SET p.status='cancelled' WHERE p.status='queued' "
            "AND m.intent='news'"
        )
    )


